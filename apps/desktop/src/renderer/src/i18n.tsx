export function detectInitialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch {
    /* localStorage 不可用时忽略 */
  }
  // 中文产品首次启动优先中文；显式保存的英文选择仍在上方保留。
  return 'zh';
}

// 模块级当前语言：供 util.ts 等非 React 上下文读取（由 Provider 同步）。
let currentLang: Lang = detectInitialLang();
export function getLang(): Lang {
  return currentLang;
}

function lookup(lang: Lang, key: string): string {
  const val = key.split('.').reduce<unknown>(
    (acc, part) => (acc && typeof acc === 'object' ? (acc as Record<string, unknown>)[part] : undefined),
    STRINGS[lang],
  );
  if (typeof val === 'string') return val;
  // 回退到中文，避免缺键时直接显示路径。
  const fallback = key.split('.').reduce<unknown>(
    (acc, part) => (acc && typeof acc === 'object' ? (acc as Record<string, unknown>)[part] : undefined),
    STRINGS.zh,
  );
  return typeof fallback === 'string' ? fallback : key;
}

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = lookup(lang, key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return s;
}

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Translate;
}

const I18nContext = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }): React.ReactElement {
  const [lang, setLangState] = useState<Lang>(() => detectInitialLang());

  useEffect(() => {
    currentLang = lang;
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch {
      /* 忽略持久化失败 */
    }
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    // 同步给主进程，供更新弹窗等原生 UI 本地化
    void window.api?.settings?.set('lang', lang).catch(() => undefined);
  }, [lang]);

  const setLang = useCallback((l: Lang) => setLangState(l), []);
  const t = useCallback<Translate>((key, vars) => translate(lang, key, vars), [lang]);

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
